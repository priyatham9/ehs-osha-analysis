#!/usr/bin/env python3
"""Write outputs/headline.json: the one canonical set of headline numbers.

The headline finding of this repository has been quoted in several shapes
across the author's repositories and sites (2.07% / 96.7% / 29.7x here, 2.24% /
86.9% / 7.6x and 1.53% / 87% in the earlier ehs-benchmarks work). This file
settles one set, states exactly what each number means, and adds the same
figures with the single largest filing left out, because that one filing holds
88.8% of every hour ever reported and would otherwise carry the story alone.

Everything here is derived from committed pipeline outputs, never typed in:

    outputs/summary.json                          quality.pooled, quality.by_year
    outputs/tables/quality_top50_implausible_hours.csv   the largest filing
    outputs/tables/reconciliation_panels.csv      the ehs-benchmarks comparison

Usage:
    python3 scripts/build_headline.py          # write outputs/headline.json
    python3 scripts/build_headline.py --check  # exit 1 if the file is stale

Stdlib only.
"""

from __future__ import annotations

import argparse
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
SUMMARY = OUT / "summary.json"
TOP50 = OUT / "tables" / "quality_top50_implausible_hours.csv"
RECON = OUT / "tables" / "reconciliation_panels.csv"
HEADLINE = OUT / "headline.json"

# TRIR = recordable cases x 200,000 / hours worked (OSHA's definition).
TRIR_HOURS = 200_000.0


def _r(x: float, nd: int) -> float:
    return float(round(x, nd))


def build() -> dict:
    """Return the headline dictionary from the committed outputs."""
    summary = json.loads(SUMMARY.read_text(encoding="utf-8"))
    q = summary["quality"]
    p = q["pooled"]
    cfg = q["screen_config"]

    n, k = int(p["n_filings"]), int(p["n_implausible"])
    hours, cases = float(p["hours_total"]), float(p["cases_total"])
    flagged_hours = hours * float(p["hours_share_implausible"])
    flagged_cases = cases * float(p["cases_share_implausible"])
    screened_hours = hours - flagged_hours
    screened_cases = cases - flagged_cases
    trir_u = cases * TRIR_HOURS / hours
    trir_s = screened_cases * TRIR_HOURS / screened_hours

    # The single largest filing by hours (row 1 of the top-50 table).
    with TOP50.open(encoding="utf-8", newline="") as fh:
        top = next(csv.DictReader(fh))
    o_hours = float(top["total_hours_worked"])
    o_cases = float(top["recordable_cases"])
    o_hpe = float(top["hours_per_employee"])
    o_flagged = not (cfg["min_hours_per_employee"] <= o_hpe <= cfg["max_hours_per_employee"])
    if not o_flagged:
        raise SystemExit("largest filing is not flagged; the ex-outlier arithmetic below assumes it is")

    # Same screen, same panel, that one filing removed. It is flagged, so the
    # screened side does not change; only the unscreened denominator does.
    n2, k2 = n - 1, k - 1
    hours2, cases2 = hours - o_hours, cases - o_cases
    flagged_hours2 = flagged_hours - o_hours
    flagged_cases2 = flagged_cases - o_cases
    trir_u2 = cases2 * TRIR_HOURS / hours2

    by_year = []
    for y in q["by_year"]:
        by_year.append({
            "year": int(float(y["label"])),
            "n_filings": int(y["n_filings"]),
            "flagged_share_pct": _r(100 * y["implausible_share"], 2),
            "hours_share_flagged_pct": _r(100 * y["hours_share_implausible"], 1),
            "trir_unscreened": _r(y["aggregate_trir_unscreened"], 3),
            "trir_screened": _r(y["aggregate_trir_screened"], 3),
            "ratio": _r(y["ratio_screened_to_unscreened"], 2),
        })
    ratios = [y["ratio"] for y in by_year]

    with RECON.open(encoding="utf-8", newline="") as fh:
        old = next(r for r in csv.DictReader(fh) if r["panel"] == "old")

    return {
        "about": ("Canonical headline numbers for the OSHA ITA hours-denominator finding. "
                  "Quote these, with their definition, and nothing else. "
                  "Generated by scripts/build_headline.py from committed outputs; do not edit by hand."),
        "definition": {
            "data": "OSHA Injury Tracking Application Form 300A establishment filings, calendar years 2016-2024, pooled",
            "deduplication": "as in src/ehs_osha/load.py (see README, Methodology)",
            "screen": ("a filing is flagged implausible when hours worked per average employee is outside "
                       f"{cfg['min_hours_per_employee']:g}-{cfg['max_hours_per_employee']:g} per year, or hours or employees "
                       "are missing, non-positive or negative (src/ehs_osha/quality.py)"),
            "trir": "aggregate TRIR = sum of recordable cases x 200,000 / sum of hours worked (ratio of sums)",
            "ratio": "aggregate TRIR with flagged filings removed / aggregate TRIR as published",
        },
        "headline": {
            "n_filings": n,
            "n_flagged": k,
            "flagged_share_pct": _r(100 * k / n, 2),
            "hours_share_flagged_pct": _r(100 * flagged_hours / hours, 2),
            "cases_share_flagged_pct": _r(100 * flagged_cases / cases, 2),
            "trir_unscreened": _r(trir_u, 3),
            "trir_screened": _r(trir_s, 3),
            "ratio": _r(trir_s / trir_u, 1),
            "one_line": (f"{k:,} of {n:,} filings ({100 * k / n:.2f}%) fail the hours screen; they hold "
                         f"{100 * flagged_hours / hours:.2f}% of all reported hours and {100 * flagged_cases / cases:.2f}% "
                         f"of cases, so aggregate TRIR moves from {trir_u:.3f} to {trir_s:.3f} ({trir_s / trir_u:.1f}x)."),
        },
        "largest_filing": {
            "establishment_id": int(float(top["establishment_id"])),
            "year": int(float(top["year_filing_for"])),
            "annual_average_employees": int(float(top["annual_average_employees"])),
            "total_hours_worked": int(o_hours),
            "recordable_cases": int(o_cases),
            "share_of_all_hours_pct": _r(100 * o_hours / hours, 2),
        },
        "excluding_largest_filing": {
            "n_filings": n2,
            "n_flagged": k2,
            "flagged_share_pct": _r(100 * k2 / n2, 2),
            "hours_share_flagged_pct": _r(100 * flagged_hours2 / hours2, 2),
            "cases_share_flagged_pct": _r(100 * flagged_cases2 / cases2, 2),
            "trir_unscreened": _r(trir_u2, 3),
            "trir_screened": _r(trir_s, 3),
            "ratio": _r(trir_s / trir_u2, 2),
            "one_line": (f"Leaving out that one filing, the flagged {100 * k2 / n2:.2f}% still hold "
                         f"{100 * flagged_hours2 / hours2:.1f}% of reported hours and the correction is "
                         f"{trir_s / trir_u2:.1f}x ({trir_u2:.3f} to {trir_s:.3f})."),
        },
        "by_year": by_year,
        "by_year_ratio_range": [min(ratios), max(ratios)],
        "earlier_ehs_benchmarks_figures": {
            "status": "superseded; not reproducible from committed data",
            "published": "1.18M filings, 2.24% flagged, 86.9% of hours, TRIR 0.45 to 3.41, 7.58x (CY2023-2025 snapshot, 100-4,000 screen)",
            "closest_reproduction": {
                "panel": "CY2023-2024, screen 100-4,000 hours per employee (outputs/tables/reconciliation_panels.csv, panel=old)",
                "n_filings": int(old["n_filings"]),
                "flagged_share_pct": _r(100 * float(old["implausible_share"]), 2),
                "hours_share_flagged_pct": _r(100 * float(old["hours_share_implausible"]), 1),
                "trir_unscreened": _r(float(old["aggregate_trir_unscreened"]), 3),
                "trir_screened": _r(float(old["aggregate_trir_screened"]), 3),
                "ratio": _r(float(old["ratio_screened_to_unscreened"]), 2),
            },
        },
        "sources": [
            "outputs/summary.json (quality.pooled, quality.by_year, quality.screen_config)",
            "outputs/tables/quality_top50_implausible_hours.csv (row 1)",
            "outputs/tables/reconciliation_panels.csv (panel=old)",
        ],
    }


def render(d: dict) -> str:
    return json.dumps(d, indent=2, ensure_ascii=False) + "\n"


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if outputs/headline.json is stale")
    args = ap.parse_args(argv)
    text = render(build())
    if args.check:
        if not HEADLINE.exists() or HEADLINE.read_text(encoding="utf-8") != text:
            print("outputs/headline.json is stale; run python3 scripts/build_headline.py", file=sys.stderr)
            return 1
        print("outputs/headline.json is current")
        return 0
    HEADLINE.write_text(text, encoding="utf-8")
    print(f"wrote {HEADLINE.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
