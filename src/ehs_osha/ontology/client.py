    @property
    def peer_groups(self) -> PeerGroupSet:
        return PeerGroupSet(self.store, self.store.objects('PeerGroup'))

    def get_peer_group(self, peer_group_key: str) -> PeerGroup:
        return PeerGroup.from_object(self.store, self.store.get('PeerGroup', peer_group_key))

    @property
    def quality_flags(self) -> QualityFlagSet:
        return QualityFlagSet(self.store, self.store.objects('QualityFlag'))

    def get_quality_flag(self, flag: str) -> QualityFlag:
        return QualityFlag.from_object(self.store, self.store.get('QualityFlag', flag))

    def flag_filing_implausible(self, filing: Union[Filing, str], reason: Literal['hours_inconsistent_with_operations', 'company_wide_hours_reported', 'employee_count_mistyped', 'case_counts_inconsistent', 'other'], note: Optional[str] = None, *, actor: str) -> ActionLogEntry:
        """Record an analyst judgement that a form cannot be right although the automatic screen passed it. The filing then leaves every screened aggregate."""
        values: dict = {}
        values['filing'] = filing.filing_id if isinstance(filing, Filing) else filing
        values['reason'] = reason
        if note is not None:
            values['note'] = note
        return self.store.apply('flag_filing_implausible', values, actor=actor)

    def clear_analyst_flag(self, filing: Union[Filing, str], note: str, *, actor: str) -> ActionLogEntry:
        """Withdraw an analyst flag, for example after the establishment confirms its hours. A justification is mandatory."""
        values: dict = {}
        values['filing'] = filing.filing_id if isinstance(filing, Filing) else filing
        values['note'] = note
        return self.store.apply('clear_analyst_flag', values, actor=actor)

    def exclude_from_benchmark(self, filing: Union[Filing, str], reason: Literal['not_comparable_to_peers', 'company_wide_hours_reported', 'under_review', 'other'], note: Optional[str] = None, *, actor: str) -> ActionLogEntry:
        """Keep a plausible filing out of aggregates and peer benchmarks because the site is not comparable to its peers."""
        values: dict = {}
        values['filing'] = filing.filing_id if isinstance(filing, Filing) else filing
        values['reason'] = reason
        if note is not None:
            values['note'] = note
        return self.store.apply('exclude_from_benchmark', values, actor=actor)

    def restore_to_benchmark(self, filing: Union[Filing, str], note: str, *, actor: str) -> ActionLogEntry:
        """Return an excluded filing to aggregates and peer benchmarks. A justification is mandatory."""
        values: dict = {}
        values['filing'] = filing.filing_id if isinstance(filing, Filing) else filing
        values['note'] = note
        return self.store.apply('restore_to_benchmark', values, actor=actor)
