class OntologyClient:
    """Typed entry point over an ObjectStore: object sets, lookups and actions."""

    def __init__(self, store: ObjectStore) -> None:
        self.store = store

    @property
    def establishments(self) -> EstablishmentSet:
        return EstablishmentSet(self.store, self.store.objects('Establishment'))

    def get_establishment(self, establishment_id: str) -> Establishment:
        return Establishment.from_object(self.store, self.store.get('Establishment', establishment_id))

    @property
    def filings(self) -> FilingSet:
        return FilingSet(self.store, self.store.objects('Filing'))

    def get_filing(self, filing_id: str) -> Filing:
        return Filing.from_object(self.store, self.store.get('Filing', filing_id))

    @property
    def reporting_years(self) -> ReportingYearSet:
        return ReportingYearSet(self.store, self.store.objects('ReportingYear'))

