"""Generate a typed Python client (``client.py``) from ``spec.json``.

This follows the pattern of an ontology SDK: object types become typed
dataclasses, links become typed methods that return typed object sets, and
action types become typed methods whose arguments are the action parameters
(with ``Literal`` types for parameters that declare ``allowed_values``). It is an
independent design on public data and is not affiliated with Palantir.

The generated module is committed. ``scripts/generate_ontology_client.py
--check`` (run in CI and in the tests) fails when it no longer matches the spec.
Generation is deterministic: the same spec always yields the same text.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional

from .spec import OntologySpec, load_spec

PY_TYPES = {
    "string": "str",
    "integer": "int",
    "double": "float",
    "boolean": "bool",
    "timestamp": "str",
}


def snake(name: str) -> str:
    """CamelCase -> snake_case."""
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).lower()


def plural(name: str) -> str:
    """Naive English plural of a snake_case name (y -> ies, otherwise s)."""
    return name[:-1] + "ies" if name.endswith("y") else name + "s"


def _doc(text: str, indent: str) -> str:
    text = " ".join(text.split()).replace('"""', "'''")
    return f'{indent}"""{text}"""\n'


def _prop_type(prop: Dict[str, Any]) -> str:
    base = PY_TYPES[prop["type"]]
    return f"Optional[{base}]" if prop.get("nullable") else base


def _param_type(param: Dict[str, Any], spec: OntologySpec) -> str:
    if param["type"] == "object_reference":
        ot = param["object_type"]
        pk = spec.object_types[ot]["primary_key"]
        pk_type = PY_TYPES[spec.properties(ot)[pk]["type"]]
        return f"Union[{ot}, {pk_type}]"
    if "allowed_values" in param:
        values = ", ".join(repr(v) for v in param["allowed_values"])
        return f"Literal[{values}]"
    return PY_TYPES[param["type"]]


def generate(spec: Optional[OntologySpec] = None) -> str:
    """Return the text of the typed client for ``spec`` (default: bundled spec)."""
    spec = spec or load_spec()
    raw = spec.raw
    out: List[str] = []
    w = out.append
    onto = raw["ontology"]
    w('"""Typed client for the OSHA ITA ontology.\n\n')
    w("GENERATED by scripts/generate_ontology_client.py from spec.json. Do not edit by\n")
    w("hand: change the spec and regenerate. ``--check`` fails when this file drifts.\n\n")
    w(f"Ontology: {onto['api_name']} version {onto['version']}. Independent design on public\n")
    w("data; not affiliated with Palantir.\n")
    w('"""\n\n')
    w("from __future__ import annotations\n\n")
    w("from dataclasses import dataclass, field\n")
    w("from typing import Any, Callable, ClassVar, Iterator, Literal, Optional, Union\n\n")
    w("import pandas as pd\n\n")
    w("from .runtime import ActionLogEntry, ObjectSet, ObjectStore, OntologyObject\n\n")
    w("_UNSET: Any = object()\n\n")
    names = list(spec.object_types)
    w("__all__ = [\n")
    for n in names:
        w(f'    "{n}",\n    "{n}Set",\n')
    w('    "OntologyClient",\n]\n')

    for ot_name, ot in spec.object_types.items():
        props = ot["properties"]
        w(f"\n\n@dataclass(frozen=True)\nclass {ot_name}:\n")
        w(_doc(ot["description"], "    "))
        w(f'\n    OBJECT_TYPE: ClassVar[str] = "{ot_name}"\n\n')
        for p in props:
            w(f"    {p['api_name']}: {_prop_type(p)}\n")
        w("    _store: ObjectStore = field(repr=False, compare=False)\n\n")
        w("    @classmethod\n")
        w(f"    def from_object(cls, store: ObjectStore, obj: OntologyObject) -> {ot_name}:\n")
        w("        p = obj.properties\n        return cls(\n")
        for p in props:
            w(f"            {p['api_name']}=p[{p['api_name']!r}],\n")
        w("            _store=store,\n        )\n")
        for lname, hop in spec.links_from(ot_name).items():
            tgt = hop["to"]
            many = hop["link"]["cardinality"] == "many_to_many" or hop["direction"] == "reverse"
            w(f"\n    def {lname}(self) -> {tgt}Set:\n")
            w(_doc(hop["link"]["description"] + (" Many objects." if many else " At most one object."), "        "))
            w(f"        obj = self._store.get({ot_name!r}, self.{ot['primary_key']})\n")
            w(f"        return {tgt}Set(self._store, self._store.linked(obj, {lname!r}))\n")

        w(f"\n\nclass {ot_name}Set:\n")
        w(_doc(f"A set of {ot_name} objects (typed wrapper over ObjectSet).", "    "))
        w(f'\n    OBJECT_TYPE: ClassVar[str] = "{ot_name}"\n\n')
        w("    def __init__(self, store: ObjectStore, object_set: ObjectSet) -> None:\n")
        w("        self._store = store\n        self._set = object_set\n\n")
        w(f"    def __iter__(self) -> Iterator[{ot_name}]:\n")
        w("        for obj in self._set:\n")
        w(f"            yield {ot_name}.from_object(self._store, obj)\n\n")
        w("    def __len__(self) -> int:\n        return len(self._set)\n\n")
        w("    def count(self) -> int:\n        return self._set.count()\n\n")
        w("    def primary_keys(self) -> list:\n        return self._set.primary_keys()\n\n")
        w("    def to_frame(self) -> pd.DataFrame:\n        return self._set.to_frame()\n\n")
        w(f"    def one(self) -> Optional[{ot_name}]:\n")
        w("        obj = self._set.one()\n")
        w(f"        return None if obj is None else {ot_name}.from_object(self._store, obj)\n\n")
        w(f"    def filter(self, predicate: Callable[[{ot_name}], bool]) -> {ot_name}Set:\n")
        w(f"        keep = [o.{ot['primary_key']} for o in self if predicate(o)]\n")
        w(f"        return {ot_name}Set(self._store, ObjectSet(self._store, {ot_name!r}, keep))\n\n")
        sig = ", ".join(f"{p['api_name']}: {_prop_type(p)} = _UNSET" for p in props)
        w(f"    def where(self, *, {sig}) -> {ot_name}Set:\n")
        w(_doc("Keep objects whose properties equal every argument given (None is a value).", "        "))
        w("        args = dict(locals())\n")
        w("        given = {k: v for k, v in args.items() if k != 'self' and v is not _UNSET}\n")
        w(f"        return {ot_name}Set(self._store, self._set.where(**given))\n")
        for lname, hop in spec.links_from(ot_name).items():
            tgt = hop["to"]
            w(f"\n    def {lname}(self) -> {tgt}Set:\n")
            w(_doc("Search around: follow this link from every object in the set.", "        "))
            w(f"        return {tgt}Set(self._store, self._set.search_around({lname!r}))\n")

    w("\n\nclass OntologyClient:\n")
    w(_doc("Typed entry point over an ObjectStore: object sets, lookups and actions.", "    "))
    w("\n    def __init__(self, store: ObjectStore) -> None:\n        self.store = store\n")
    for ot_name, ot in spec.object_types.items():
        coll = plural(snake(ot_name))
        pk = ot["primary_key"]
        pk_type = PY_TYPES[spec.properties(ot_name)[pk]["type"]]
        w("\n    @property\n")
        w(f"    def {coll}(self) -> {ot_name}Set:\n")
        w(f"        return {ot_name}Set(self.store, self.store.objects({ot_name!r}))\n")
        w(f"\n    def get_{snake(ot_name)}(self, {pk}: {pk_type}) -> {ot_name}:\n")
        w(f"        return {ot_name}.from_object(self.store, self.store.get({ot_name!r}, {pk}))\n")
    for an, act in spec.action_types.items():
        params = act["parameters"]
        req = [p for p in params if p.get("required")]
        opt = [p for p in params if not p.get("required")]
        parts = ["self"]
        parts += [f"{p['api_name']}: {_param_type(p, spec)}" for p in req]
        parts += [f"{p['api_name']}: Optional[{_param_type(p, spec)}] = None" for p in opt]
        sig = ", ".join(parts) + ", *, actor: str"
        w(f"\n    def {an}({sig}) -> ActionLogEntry:\n")
        w(_doc(act["description"], "        "))
        w("        values: dict = {}\n")
        for p in params:
            n = p["api_name"]
            if p["type"] == "object_reference":
                pk = spec.object_types[p["object_type"]]["primary_key"]
                src = f"{n}.{pk} if isinstance({n}, {p['object_type']}) else {n}"
            else:
                src = n
            if p.get("required"):
                w(f"        values[{n!r}] = {src}\n")
            else:
                w(f"        if {n} is not None:\n            values[{n!r}] = {src}\n")
        w(f"        return self.store.apply({an!r}, values, actor=actor)\n")
    return "".join(out)
