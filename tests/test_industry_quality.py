"""Tests for the industry / size / year filing-quality view.

``docs/INDUSTRY_QUALITY.md`` is generated by :mod:`ehs_osha.industry_quality`
from committed tables. These tests regenerate it in memory and fail if the
committed document differs, so no number in it can be typed by hand.
"""

from __future__ import annotations

import math
import unittest

import _context  # noqa: F401
from ehs_osha import industry_quality as iq

TABLES = _context.ROOT / "outputs" / "tables"
DOC = _context.ROOT / "docs" / "INDUSTRY_QUALITY.md"


def tables_available() -> bool:
    """Return True if the committed quality tables are present."""
    return (TABLES / "quality_by_naics2.csv").exists() and (
        TABLES / "quality_top50_implausible_hours.csv"
    ).exists()


class TestStatistics(unittest.TestCase):
    def test_wilson_known_value(self) -> None:
        # Wilson 95% for 10/100 is (0.0552, 0.1744) to 4 dp.
        lo, hi = iq.wilson_interval(10, 100)
        self.assertAlmostEqual(lo, 0.05523, places=4)
        self.assertAlmostEqual(hi, 0.17437, places=4)

    def test_wilson_edges(self) -> None:
        lo, hi = iq.wilson_interval(0, 50)
        self.assertAlmostEqual(lo, 0.0, places=12)
        self.assertGreater(hi, 0.0)
        lo, hi = iq.wilson_interval(50, 50)
        self.assertAlmostEqual(hi, 1.0, places=12)
        with self.assertRaises(ValueError):
            iq.wilson_interval(3, 0)

    def test_chi2_sf_matches_closed_forms(self) -> None:
        # df=2 survival is exp(-x/2).
        self.assertAlmostEqual(iq.chi2_sf_even_df(3.0, 2), math.exp(-1.5), places=12)
        # 95th percentile of chi-square(8) is 15.507.
        self.assertAlmostEqual(iq.chi2_sf_even_df(15.5073, 8), 0.05, places=4)
        self.assertEqual(iq.chi2_sf_even_df(0.0, 8), 1.0)
        with self.assertRaises(ValueError):
            iq.chi2_sf_even_df(1.0, 3)

    def test_chi2_homogeneity_zero_when_equal(self) -> None:
        stat, df = iq.chi2_homogeneity([10, 20, 30], [100, 200, 300])
        self.assertAlmostEqual(stat, 0.0, places=12)
        self.assertEqual(df, 2)

    def test_size_band_matches_pipeline_edges(self) -> None:
        self.assertEqual(iq.size_band(7.0), "001-019")
        self.assertEqual(iq.size_band(133.0), "100-249")
        self.assertEqual(iq.size_band(14292.0), "1000+")
        self.assertIsNone(iq.size_band(float("nan")))


@unittest.skipUnless(tables_available(), "committed outputs/tables not present")
class TestDocument(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.analysis = iq.analyse(TABLES)
        cls.text = iq.render(cls.analysis)

    def test_committed_doc_matches_script_output(self) -> None:
        self.assertTrue(DOC.exists(), "run python3 -m ehs_osha.industry_quality")
        self.assertEqual(
            DOC.read_text(encoding="utf-8"),
            self.text,
            "docs/INDUSTRY_QUALITY.md is stale; run python3 -m ehs_osha.industry_quality",
        )

    def test_sector_counts_reconcile_to_pooled(self) -> None:
        a = self.analysis
        kept_n = sum(s["n"] for s in a["sectors_by_share"])
        kept_k = sum(s["k"] for s in a["sectors_by_share"])
        self.assertEqual(kept_n + a["other"]["n"], a["pooled"]["n"])
        self.assertEqual(kept_k + a["other"]["k"], a["pooled"]["k"])

    def test_year_counts_reconcile_to_pooled(self) -> None:
        a = self.analysis
        self.assertEqual(sum(y["n"] for y in a["years"]), a["pooled"]["n"])
        self.assertEqual(sum(y["k"] for y in a["years"]), a["pooled"]["k"])

    def test_top50_fully_assigned(self) -> None:
        a = self.analysis
        self.assertEqual(sum(b["top_n"] for b in a["bands"]) + a["top_missing_band"], 50)
        self.assertEqual(sum(y["top_n"] for y in a["years"]), 50)

    def test_rankings_sorted(self) -> None:
        shares = [s["share"] for s in self.analysis["sectors_by_share"]]
        self.assertEqual(shares, sorted(shares, reverse=True))
        ratios = [s["ratio"] or 0.0 for s in self.analysis["sectors_by_ratio"]]
        self.assertEqual(ratios, sorted(ratios, reverse=True))

    def test_style(self) -> None:
        self.assertNotIn("\u2014", self.text)
        self.assertTrue(self.text.endswith("\n"))


if __name__ == "__main__":
    unittest.main()
